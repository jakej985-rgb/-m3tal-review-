package slop_test

import (
	review "github.com/jakej985-rgb/m3tal-review/internal/review"
	"os/exec"
	"strings"
	"testing"
)

// slopMessages stages source as main.go in a temp repo and returns the
// "line:message" of every finding from the AST path.
func slopMessages(t *testing.T, source string) []string {
	t.Helper()
	repoDir := setupSlopTestRepo(t, source)
	cmd := exec.Command("git", "diff", "--cached", "-U0")
	cmd.Dir = repoDir
	out, err := cmd.Output()
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, f := range (review.SlopRule{RepositoryRoot: repoDir}).Check(string(out)) {
		got = append(got, f.Message)
	}
	return got
}

func regexMessages(file, added string) []string {
	var body strings.Builder
	n := 0
	for _, l := range strings.Split(added, "\n") {
		body.WriteString("+" + l + "\n")
		n++
	}
	diff := "diff --git a/" + file + " b/" + file + "\nnew file mode 100644\n--- /dev/null\n+++ b/" + file +
		"\n@@ -0,0 +1," + string(rune('0'+n)) + " @@\n" + body.String()
	var got []string
	for _, f := range (review.SlopRule{}).Check(diff) {
		got = append(got, f.Message)
	}
	return got
}

func TestSlopEmptyBlockWithCommentIsAllowed(t *testing.T) {
	got := slopMessages(t, "package main\nfunc f(err error) {\n\tif err != nil {\n\t\t// intentionally ignored\n\t}\n}\n")
	if len(got) != 0 {
		t.Fatalf("commented block should pass, got %v", got)
	}
}

func TestSlopTrulyEmptyBlockStillFlagged(t *testing.T) {
	got := slopMessages(t, "package main\nfunc f(err error) {\n\tif err != nil {\n\t}\n\tfor i := 0; i < 3; i++ {\n\t}\n}\n")
	if len(got) != 2 {
		t.Fatalf("want 2 empty-block findings, got %v", got)
	}
}

func TestSlopStubsAndBlockingConstructsAreNotEmptyBlocks(t *testing.T) {
	src := "package main\ntype T struct{}\nfunc (T) Noop() {}\nvar _ = func() {}\nfunc g() {\n\tselect {}\n}\nfunc h() {\n\tfor {\n\t}\n}\n"
	if got := slopMessages(t, src); len(got) != 0 {
		t.Fatalf("stubs/select{}/for{} should pass, got %v", got)
	}
}

func TestSlopElseIfChainIsNotDeepNesting(t *testing.T) {
	src := "package main\nfunc f(x int) {\n\tif x == 1 {\n\t\t_ = 1\n\t} else if x == 2 {\n\t\t_ = 2\n\t} else if x == 3 {\n\t\t_ = 3\n\t} else if x == 4 {\n\t\t_ = 4\n\t} else if x == 5 {\n\t\t_ = 5\n\t}\n}\n"
	if got := slopMessages(t, src); len(got) != 0 {
		t.Fatalf("else-if chain should pass, got %v", got)
	}
}

func TestSlopRealNestingStillFlaggedInsideElseIf(t *testing.T) {
	src := "package main\nfunc f(a, b, c, d bool) {\n\tif a {\n\t\t_ = 0\n\t} else if b {\n\t\tif c {\n\t\t\tif d {\n\t\t\t\t_ = 1\n\t\t\t}\n\t\t}\n\t}\n}\n"
	// else-if (1) -> if c (2) -> if d (3): depth 3, must NOT flag
	if got := slopMessages(t, src); len(got) != 0 {
		t.Fatalf("depth 3 should pass, got %v", got)
	}
	src = "package main\nfunc f(a, b, c, d, e bool) {\n\tif a {\n\t\tif b {\n\t\t\tif c {\n\t\t\t\tif d {\n\t\t\t\t\t_ = 1\n\t\t\t\t}\n\t\t\t}\n\t\t}\n\t}\n}\n"
	if got := slopMessages(t, src); len(got) != 1 || !strings.Contains(got[0], "nesting") {
		t.Fatalf("depth 4 must still be flagged once, got %v", got)
	}
}

func TestSlopGeneratedGoFileSkipped(t *testing.T) {
	src := "// Code generated by tool. DO NOT EDIT.\n\npackage main\nfunc f(b bool) {\n\tif b == true {\n\t}\n}\n"
	if got := slopMessages(t, src); len(got) != 0 {
		t.Fatalf("generated file should be skipped, got %v", got)
	}
}

func TestSlopRegexBooleanCoversAllFourForms(t *testing.T) {
	for _, line := range []string{"if a == true {", "if a == false {", "if a != true {", "if a != false {"} {
		if got := regexMessages("x.go", line); len(got) != 1 || got[0] != "Redundant boolean comparison" {
			t.Errorf("%q: want boolean finding, got %v", line, got)
		}
	}
}

func TestSlopRegexEmptyBlockOnlyForControlFlow(t *testing.T) {
	for _, line := range []string{"const opts = {};", "m := map[string]struct{}{}", "var x interface{} = nil", "func Noop() {}"} {
		if got := regexMessages("x.js", line); len(got) != 0 {
			t.Errorf("%q should not be flagged, got %v", line, got)
		}
	}
	if got := regexMessages("x.js", "if (ok) {}"); len(got) != 1 {
		t.Errorf("empty if should be flagged, got %v", got)
	}
}

func TestSlopRegexSkipsNonCodeFiles(t *testing.T) {
	for _, f := range []string{"cfg.yaml", "data.json", "README.md", "Makefile", "script.py"} {
		if got := regexMessages(f, "\t\t\t\tx == true {}"); len(got) != 0 {
			t.Errorf("%s should not be scanned, got %v", f, got)
		}
	}
}

func TestSlopMalformedFilesAreReportedIndividually(t *testing.T) {
	diff := "diff --git a/a.js b/a.js\nnew file mode 100644\n--- /dev/null\n+++ b/a.js\n@@ -0,0 +1 @@\n+if (x === true) {\n" +
		"diff --git a/b.js b/b.js\nnew file mode 100644\n--- /dev/null\n+++ b/b.js\n@@ -0,0 +1,2 @@\n+ok();\n+if (y !== false) {\n"
	fs := (review.SlopRule{}).Check(diff)
	if len(fs) != 2 || fs[0].Rule != "code-slop-analysis-error" || fs[0].File != "a.js" || fs[0].Line != 0 || fs[1].Rule != "code-slop-analysis-error" || fs[1].File != "b.js" || fs[1].Line != 0 {
		t.Fatalf("unexpected findings: %+v", fs)
	}
}

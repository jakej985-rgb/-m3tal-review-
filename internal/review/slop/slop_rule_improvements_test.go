func TestSlopMalformedFilesAreReportedIndividually(t *testing.T) {
	diff := "diff --git a/a.js b/a.js\nnew file mode 100644\n--- /dev/null\n+++ b/a.js\n@@ -0,0 +1 @@\n+if (x === true) {\n" +
		"diff --git a/b.js b/b.js\nnew file mode 100644\n--- /dev/null\n+++ b/b.js\n@@ -0,0 +1,2 @@\n+ok();\n+if (y !== false) {\n"
	fs := (review.SlopRule{}).Check(diff)
	if len(fs) != 2 || fs[0].Rule != "code-slop-analysis-error" || fs[0].File != "a.js" || fs[0].Line != 0 || fs[1].Rule != "code-slop-analysis-error" || fs[1].File != "b.js" || fs[1].Line != 0 {
		t.Fatalf("unexpected findings: %+v", fs)
	}
}

func TestSlopDeferBeforeErrCheckAndWaitGroupAdd(t *testing.T) {
	src := `package main

import (
	"net/http"
	"sync"
)

func fetch(url string) error {
	resp, err := http.Get(url)
	defer resp.Body.Close()
	if err != nil {
		return err
	}
	return nil
}

func spawn(wg *sync.WaitGroup) {
	go func() {
		wg.Add(1)
		defer wg.Done()
	}()
}
`
	got := slopMessages(t, src)
	foundDefer := false
	foundWg := false
	for _, msg := range got {
		if msg == "Resource closed with defer before checking error" {
			foundDefer = true
		}
		if msg == "sync.WaitGroup.Add called inside spawned goroutine" {
			foundWg = true
		}
	}
	if !foundDefer {
		t.Errorf("expected 'Resource closed with defer before checking error', got %v", got)
	}
	if !foundWg {
		t.Errorf("expected 'sync.WaitGroup.Add called inside spawned goroutine', got %v", got)
	}
}


package scanner

import (
	"os"
	"path/filepath"
	"testing"
)

func TestScanDiscoversManifestsAndExcludesGeneratedAndVendored(t *testing.T) {
	root := t.TempDir()
	mustWrite(t, filepath.Join(root, "go.mod"), "module example.com/demo\n")
	mustWrite(t, filepath.Join(root, "main.go"), "package main\nfunc main() {}\n")
	mustWrite(t, filepath.Join(root, "api.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage main\n")
	mustWrite(t, filepath.Join(root, "node_modules", "pkg", "index.js"), "console.log(1);\n")

	inv, err := Scan(root, ScanOptions{})
	if err != nil {
		t.Fatalf("Scan failed: %v", err)
	}
	if len(inv.Manifests["go.mod"]) != 1 {
		t.Fatalf("expected go.mod manifest, got %+v", inv.Manifests)
	}
	var sawPB, sawVendor bool
	for _, f := range inv.Files {
		if f.Path == "api.pb.go" {
			sawPB = true
			if !f.Generated || !f.Excluded {
				t.Errorf("expected api.pb.go to be marked generated & excluded: %+v", f)
			}
		}
		if f.Path == "node_modules" {
			sawVendor = true
			if !f.Excluded {
				t.Errorf("expected node_modules to be excluded: %+v", f)
			}
		}
	}
	if !sawPB || !sawVendor {
		t.Fatalf("expected both api.pb.go and node_modules in inventory: %+v", inv.Files)
	}
}

func TestScanExcludesOutsideSymlink(t *testing.T) {
	outside := t.TempDir()
	secretPath := filepath.Join(outside, "secret.txt")
	mustWrite(t, secretPath, "TOP_SECRET_VALUE")

	root := t.TempDir()
	if err := os.Symlink(secretPath, filepath.Join(root, "leak.txt")); err != nil {
		t.Skipf("symlink unsupported: %v", err)
	}

	inv, err := Scan(root, ScanOptions{})
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}
	for _, f := range inv.Files {
		if f.Path == "leak.txt" {
			if !f.Excluded || f.Header != "" {
				t.Fatalf("expected outside symlink to be excluded with empty header, got %+v", f)
			}
			return
		}
	}
	t.Fatalf("leak.txt not found in inventory")
}

func mustWrite(t *testing.T, p, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(p, []byte(content), 0644); err != nil {
		t.Fatalf("write %s: %v", p, err)
	}
}
